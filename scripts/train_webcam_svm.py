"""Train and evaluate a webcam-consistent HOG (1764-dim) LinearSVC model.

Strict scientific & integrity guarantees:
1. Uses ONLY confirmed samples (`label_confirmed == True`) with complete 6-field metadata
   from a validated split manifest (`split.csv` generated by `split_webcam_collection.py`).
2. Re-verifies ZERO leakage across train/validation/test:
   - Zero participant_id overlap across splits (participant-grouped split).
   - Zero `(participant_id, session_id, gesture_instance_id)` overlap across splits.
   - Zero exact `image_sha256` overlap across splits.
3. Refuses to train or fabricate metrics when classes are missing or data is insufficient.
4. Extracts 1764-dim HOG features using `src.preprocess.webcam_features.extract_webcam_hog_feature`,
   guaranteeing 100% preprocessing parity with live SignVision inference.
5. Selects `(preprocess_mode, C)` strictly on `validation` (LinearSVC only — never Random Forest),
   locks the winner, and evaluates ONCE on independent `test`.
6. Compares the newly trained LinearSVC against the existing production baseline model
   (`models/svm/svm_final_c0_01.joblib`, both Legacy and Method 3B) on the EXACT SAME test set.
7. Saves the new model separately; NEVER overwrites `models/svm/svm_final_c0_01.joblib`.
"""

