ALL_36_LABELS = list("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ")
REQUIRED_META_FIELDS = (
    "participant_id",
    "session_id",
    "gesture_instance_id",
    "handedness",
    "background",
    "lighting",
)
DEFAULT_C_GRID = [0.01, 0.1, 1.0, 10.0]
DEFAULT_PREPROCESS_MODES = ["legacy", "method_3b"]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def load_and_verify_split_manifest(
    split_csv: Path,
    samples_dir: Path,
    require_all_36_classes: bool = True,
    min_per_class_train: int = 1,
    min_per_class_val: int = 1,
    min_per_class_test: int = 1,
) -> tuple[list[dict[str, object]], list[str]]:
    """Load split.csv, verify metadata/confirmations/leakage/class counts, and load sample paths."""
    if not split_csv.is_file():
        raise FileNotFoundError(f"Split manifest not found: {split_csv}")
    if not samples_dir.is_dir():
        raise FileNotFoundError(f"Samples directory not found: {samples_dir}")

    with split_csv.open("r", encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError("Split manifest is empty.")

    errors: list[str] = []
    participant_splits: dict[str, set[str]] = {}
    instance_splits: dict[str, set[str]] = {}
    sha_splits: dict[str, set[str]] = {}
    counts: Counter[tuple[str, str]] = Counter()
    records: list[dict[str, object]] = []

    for row in rows:
        fname = str(row.get("folder_name", "")).strip()
        split = str(row.get("split", "")).strip()
        label = str(row.get("true_label", "")).strip().upper()
        confirmed = str(row.get("label_confirmed", "")).strip().lower() == "true"

        if split not in ("train", "validation", "test"):
            errors.append(f"{fname}: invalid split '{split}'")
            continue
        if label not in ALL_36_LABELS:
            errors.append(f"{fname}: invalid label '{label}'")
            continue
        if not confirmed:
            errors.append(f"{fname}: label_confirmed is not True")
        if require_all_36_classes and str(row.get("pilot_only", "")).strip().lower() == "true":
            errors.append(f"{fname}: marked pilot_only=True (cannot be used for production training)")

        for field in REQUIRED_META_FIELDS:
            if not str(row.get(field, "")).strip():
                errors.append(f"{fname}: missing metadata '{field}'")

        sample_dir = samples_dir / fname
        crop_path = sample_dir / "received_crop.png"
        meta_path = sample_dir / "diagnostic_metadata.json"
        if not crop_path.is_file() or not meta_path.is_file():
            errors.append(f"{fname}: missing received_crop.png or diagnostic_metadata.json in {samples_dir}")
            continue

        disk_meta = json.loads(meta_path.read_text(encoding="utf-8"))
        if not bool(disk_meta.get("label_confirmed", False)):
            errors.append(f"{fname}: on-disk diagnostic_metadata.json has label_confirmed != True")
        disk_label = str(disk_meta.get("verified_true_label") or disk_meta.get("intended_sign") or "").strip().upper()
        if disk_label != label:
            errors.append(f"{fname}: manifest label '{label}' disagrees with on-disk label '{disk_label}'")

        pid = str(row.get("participant_id", "")).strip()
        sid = str(row.get("session_id", "")).strip()
        gid = str(row.get("gesture_instance_id", "")).strip()
        inst_key = f"{pid}|{sid}|{gid}"
        file_sha = sha256_file(crop_path)

        participant_splits.setdefault(pid, set()).add(split)
        instance_splits.setdefault(inst_key, set()).add(split)
        sha_splits.setdefault(file_sha, set()).add(split)
        counts[split, label] += 1

        records.append(
            {
                "folder_name": fname,
                "split": split,
                "label": label,
                "participant_id": pid,
                "session_id": sid,
                "gesture_instance_id": gid,
                "gesture_instance_key": inst_key,
                "crop_path": crop_path,
                "disk_meta": disk_meta,
                "image_sha256": file_sha,
            }
        )

    for pid, sp_set in sorted(participant_splits.items()):
        if len(sp_set) > 1:
            errors.append(f"Participant leakage: '{pid}' appears in {sorted(sp_set)}")
    for ik, sp_set in sorted(instance_splits.items()):
        if len(sp_set) > 1:
            errors.append(f"Gesture instance leakage: '{ik}' appears in {sorted(sp_set)}")
    for digest, sp_set in sorted(sha_splits.items()):
        if len(sp_set) > 1:
            errors.append(f"Exact image SHA-256 leakage across splits: {digest[:12]} in {sorted(sp_set)}")

    expected_labels = ALL_36_LABELS if require_all_36_classes else sorted({str(r["label"]) for r in records})
    if len(expected_labels) < 2:
        errors.append("Need at least 2 distinct classes to train a classifier.")

    mins = {"train": min_per_class_train, "validation": min_per_class_val, "test": min_per_class_test}
    for sp, req_min in mins.items():
        for lbl in expected_labels:
            if counts[sp, lbl] < req_min:
                errors.append(f"{sp}: class '{lbl}' has {counts[sp, lbl]} samples (< required {req_min})")

    if errors:
        preview = "\n  - ".join(errors[:30])
        suffix = f"\n  ... and {len(errors) - 30} more errors" if len(errors) > 30 else ""
        raise ValueError(f"Training refused due to data/split gate failures ({len(errors)}):\n  - {preview}{suffix}")

    return records, expected_labels


def extract_features_for_records(
    records: list[dict[str, object]],
    class_names: list[str],
    preprocess_mode: str,
) -> tuple[np.ndarray, np.ndarray]:
    label_to_idx = {c: i for i, c in enumerate(class_names)}
    X_list: list[np.ndarray] = []
    y_list: list[int] = []
    for rec in records:
        bgr = cv2.imread(str(rec["crop_path"]))
        if bgr is None:
            raise ValueError(f"Cannot read image: {rec['crop_path']}")
        feat, _ = extract_webcam_hog_feature(
            bgr,
            preprocess_mode=preprocess_mode,
            metadata=rec["disk_meta"],  # type: ignore[arg-type]
        )
        X_list.append(feat)
        y_list.append(label_to_idx[str(rec["label"])])
    return np.asarray(X_list, dtype=np.float32), np.asarray(y_list, dtype=np.int64)


def compute_detailed_metrics(
    y_true_labels: list[str],
    y_pred_labels: list[str],
    class_names: list[str],
) -> dict[str, object]:
    acc = float(accuracy_score(y_true_labels, y_pred_labels))
    p, r, f1, _ = precision_recall_fscore_support(
        y_true_labels,
        y_pred_labels,
        labels=class_names,
        average="macro",
        zero_division=0,
    )
    report = classification_report(
        y_true_labels,
        y_pred_labels,
        labels=class_names,
        output_dict=True,
        zero_division=0,
    )
    cm = confusion_matrix(y_true_labels, y_pred_labels, labels=class_names)
    confused_pairs: list[dict[str, object]] = []
    for i, true_c in enumerate(class_names):
        for j, pred_c in enumerate(class_names):
            if i != j and cm[i, j] > 0:
                confused_pairs.append(
                    {
                        "true_class": true_c,
                        "predicted_class": pred_c,
                        "pair": f"{true_c} -> {pred_c}",
                        "count": int(cm[i, j]),
                    }
                )
    confused_pairs.sort(key=lambda x: (-int(x["count"]), str(x["pair"])))
    correct = int(sum(1 for t, pr in zip(y_true_labels, y_pred_labels) if t == pr))
    return {
        "samples": len(y_true_labels),
        "correct": correct,
        "incorrect": len(y_true_labels) - correct,
        "accuracy": acc,
        "macro_precision": float(p),
        "macro_recall": float(r),
        "macro_f1": float(f1),
        "per_class_report": report,
        "top_confused_pairs": confused_pairs[:20],
    }


def evaluate_existing_baseline_on_test(
    baseline_model_path: Path,
    test_records: list[dict[str, object]],
    class_names: list[str],
) -> dict[str, object]:
    if not baseline_model_path.is_file():
        return {"available": False, "reason": f"Baseline model not found: {baseline_model_path}"}

    predictor = SVMSignPredictor(model_path=baseline_model_path)
    y_true = [str(r["label"]) for r in test_records]
    results = {}
    for mode in ("legacy", "method_3b"):
        y_pred = []
        for r in test_records:
            bgr = cv2.imread(str(r["crop_path"]))
            # Use canonical unflipped crop + explicit experimental_webcam_mode so orientation matches live UI
            meta = r["disk_meta"]
            already_flipped = (
                False
                if str(meta.get("crop_orientation", "")).startswith("canonical_unflipped")
                else bool(meta.get("flip_input_for_model", False))
            )
            if mode == "legacy" and already_flipped:
                bgr_in = cv2.flip(bgr, 1)
                res = predictor.predict_image_bgr(bgr_in, top_k=3, experimental_webcam_mode=False, already_flipped=False)
            else:
                res = predictor.predict_image_bgr(
                    bgr,
                    top_k=3,
                    experimental_webcam_mode=(mode == "method_3b"),
                    already_flipped=already_flipped,
                )
            y_pred.append(str(res["predicted_label"]))
        results[mode] = compute_detailed_metrics(y_true, y_pred, class_names)
    return {
        "available": True,
        "baseline_model_path": str(baseline_model_path),
        "metrics_by_mode": results,
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--split-csv", type=Path, required=True, help="Validated split.csv from split_webcam_collection.py")
    p.add_argument("--samples-dir", type=Path, required=True, help="Directory containing sample_* folders")
    p.add_argument(
        "--preprocess-modes",
        nargs="+",
        choices=["legacy", "method_3b"],
        default=DEFAULT_PREPROCESS_MODES,
        help="Preprocessing modes to compare on validation (default: legacy method_3b)",
    )
    p.add_argument(
        "--c-grid",
        nargs="+",
        type=float,
        default=DEFAULT_C_GRID,
        help="LinearSVC C values to compare strictly on validation",
    )
    p.add_argument("--max-iter", type=int, default=10_000)
    p.add_argument("--min-per-class-train", type=int, default=1)
    p.add_argument("--min-per-class-val", type=int, default=1)
    p.add_argument("--min-per-class-test", type=int, default=1)
    p.add_argument(
        "--baseline-model",
        type=Path,
        default=DEFAULT_MODEL_PATH,
        help=f"Existing baseline model to compare on the exact same test set (default: {DEFAULT_MODEL_PATH})",
    )
    p.add_argument(
        "--model-output",
        type=Path,
        default=None,
        help="Separate output path for new LinearSVC model bundle (never overwrites svm_final_c0_01.joblib)",
    )
    p.add_argument(
        "--report-dir",
        type=Path,
        default=Path("results/svm/webcam_hog_svm_runs"),
        help="Output directory for validation/test reports",
    )
    p.add_argument(
        "--refit-train-val",
        action="store_true",
        help="After locking (preprocess_mode, C) on validation, refit final model on train+validation before one-shot test",
    )
    p.add_argument(
        "--allow-subset-for-tests",
        action="store_true",
        help="Allow <36 classes ONLY for automated synthetic pipeline tests (clearly tagged non-production)",
    )
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    args = parse_args(argv)

    records, class_names = load_and_verify_split_manifest(
        split_csv=args.split_csv,
        samples_dir=args.samples_dir,
        require_all_36_classes=not args.allow_subset_for_tests,
        min_per_class_train=args.min_per_class_train,
        min_per_class_val=args.min_per_class_val,
        min_per_class_test=args.min_per_class_test,
    )

    train_recs = [r for r in records if r["split"] == "train"]
    val_recs = [r for r in records if r["split"] == "validation"]
    test_recs = [r for r in records if r["split"] == "test"]

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    model_output = args.model_output or Path(f"models/svm/webcam_hog_linear_svc_{ts}.joblib")
    if model_output.resolve() == (PROJECT_ROOT / DEFAULT_MODEL_PATH).resolve():
        raise ValueError("Refusing to overwrite existing production model models/svm/svm_final_c0_01.joblib.")

    # Phase 1: Validation selection strictly on train -> validation (test is NOT touched)
    features_cache: dict[str, tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]] = {}
    val_candidates: list[dict[str, object]] = []
    fitted_val_models: dict[tuple[str, float], Pipeline] = {}

    for mode in args.preprocess_modes:
        X_tr, y_tr = extract_features_for_records(train_recs, class_names, preprocess_mode=mode)
        X_va, y_va = extract_features_for_records(val_recs, class_names, preprocess_mode=mode)
        features_cache[mode] = (X_tr, y_tr, X_va, y_va)

        for c_val in args.c_grid:
            pipe = Pipeline(
                steps=[
                    (
                        "classifier",
                        LinearSVC(
                            C=float(c_val),
                            random_state=RANDOM_STATE,
                            max_iter=args.max_iter,
                            dual="auto",
                        ),
                    )
                ]
            )
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always", ConvergenceWarning)
                t0 = time.perf_counter()
                pipe.fit(X_tr, y_tr)
                fit_s = time.perf_counter() - t0
            y_va_pred = pipe.predict(X_va)
            va_true_lbl = [class_names[i] for i in y_va]
            va_pred_lbl = [class_names[i] for i in y_va_pred]
            va_metrics = compute_detailed_metrics(va_true_lbl, va_pred_lbl, class_names)
            val_candidates.append(
                {
                    "preprocess_mode": mode,
                    "c": float(c_val),
                    "fit_seconds": round(fit_s, 4),
                    "convergence_warnings": len(caught),
                    "validation_accuracy": va_metrics["accuracy"],
                    "validation_macro_precision": va_metrics["macro_precision"],
                    "validation_macro_recall": va_metrics["macro_recall"],
                    "validation_macro_f1": va_metrics["macro_f1"],
                }
            )
            fitted_val_models[(mode, float(c_val))] = pipe

    val_candidates.sort(
        key=lambda r: (
            -float(r["validation_macro_f1"]),
            -float(r["validation_accuracy"]),
            float(r["c"]),
        )
    )
    best = val_candidates[0]
    best_mode = str(best["preprocess_mode"])
    best_c = float(best["c"])

    # Phase 2: Lock winner and evaluate ONCE on independent test
    X_tr_best, y_tr_best, X_va_best, y_va_best = features_cache[best_mode]
    if args.refit_train_val:
        X_final_fit = np.vstack([X_tr_best, X_va_best])
        y_final_fit = np.concatenate([y_tr_best, y_va_best])
        final_pipeline = Pipeline(
            steps=[
                (
                    "classifier",
                    LinearSVC(
                        C=best_c,
                        random_state=RANDOM_STATE,
                        max_iter=args.max_iter,
                        dual="auto",
                    ),
                )
            ]
        )
        t0 = time.perf_counter()
        final_pipeline.fit(X_final_fit, y_final_fit)
        final_fit_seconds = time.perf_counter() - t0
        training_scope = f"webcam train+validation ({len(X_final_fit)} samples)"
    else:
        final_pipeline = fitted_val_models[(best_mode, best_c)]
        final_fit_seconds = float(best["fit_seconds"])
        training_scope = f"webcam train only ({len(X_tr_best)} samples)"

    X_te, y_te = extract_features_for_records(test_recs, class_names, preprocess_mode=best_mode)
    y_te_pred = final_pipeline.predict(X_te)
    te_true_lbl = [class_names[i] for i in y_te]
    te_pred_lbl = [class_names[i] for i in y_te_pred]
    test_metrics = compute_detailed_metrics(te_true_lbl, te_pred_lbl, class_names)

    baseline_comparison = evaluate_existing_baseline_on_test(
        baseline_model_path=args.baseline_model,
        test_records=test_recs,
        class_names=class_names,
    )

    model_output.parent.mkdir(parents=True, exist_ok=True)
    run_dir = args.report_dir / f"run_{ts}"
    run_dir.mkdir(parents=True, exist_ok=True)

    bundle = {
        "model": final_pipeline,
        "model_family": "LinearSVC",
        "feature_schema": HOG_FEATURE_SCHEMA,
        "feature_count": HOG_FEATURE_DIM,
        "preprocess_mode": best_mode,
        "experimental_webcam_mode": best_mode == "method_3b",
        "class_names": np.asarray(class_names, dtype=str),
        "image_size": IMAGE_SIZE,
        "hog_parameters": HOG_PARAMETERS,
        "c": best_c,
        "random_state": RANDOM_STATE,
        "split_csv": str(args.split_csv),
        "split_csv_sha256": sha256_file(args.split_csv),
        "training_scope": training_scope,
        "is_full_36_class_model": (len(class_names) == 36 and not args.allow_subset_for_tests),
        "validation_selection": best,
        "test_metrics_summary": {
            "samples": test_metrics["samples"],
            "accuracy": test_metrics["accuracy"],
            "macro_f1": test_metrics["macro_f1"],
        },
    }
    joblib.dump(bundle, model_output)

    report_payload = {
        "experiment": "webcam_hog_linear_svc",
        "model_family": "LinearSVC (1764 HOG features — NOT Random Forest)",
        "feature_schema": HOG_FEATURE_SCHEMA,
        "is_full_36_class_model": bundle["is_full_36_class_model"],
        "split_csv": str(args.split_csv),
        "split_csv_sha256": bundle["split_csv_sha256"],
        "split_counts": {
            "train": len(train_recs),
            "validation": len(val_recs),
            "test": len(test_recs),
        },
        "class_names": class_names,
        "validation_candidates": val_candidates,
        "selected_on_validation": best,
        "refit_train_val": bool(args.refit_train_val),
        "final_fit_seconds": round(final_fit_seconds, 4),
        "independent_test_metrics": test_metrics,
        "baseline_comparison_same_test_set": baseline_comparison,
        "saved_model_path": str(model_output.resolve()),
    }
    report_json = run_dir / "evaluation_report.json"
    report_json.write_text(json.dumps(report_payload, indent=2, ensure_ascii=False), encoding="utf-8")

    # Export per-class CSV
    per_class_csv = run_dir / "per_class_test_metrics.csv"
    with per_class_csv.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["class", "precision", "recall", "f1_score", "support"])
        writer.writeheader()
        rep = test_metrics["per_class_report"]
        for c in class_names:
            row = rep[c]
            writer.writerow(
                {
                    "class": c,
                    "precision": round(float(row["precision"]), 6),
                    "recall": round(float(row["recall"]), 6),
                    "f1_score": round(float(row["f1-score"]), 6),
                    "support": int(row["support"]),
                }
            )

    print("================ WEBCAM HOG + LinearSVC RESULT ================")
    print(f"Selected on validation : preprocess={best_mode}, C={best_c} (Val Macro F1={best['validation_macro_f1']:.4f})")
    print(f"Independent Test Acc   : {test_metrics['accuracy']*100:.2f}% ({test_metrics['correct']}/{test_metrics['samples']})")
    print(f"Independent Test MacF1 : {test_metrics['macro_f1']:.4f}")
    print(f"Saved model (separate) : {model_output.resolve()}")
    print(f"Saved report           : {report_json.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
